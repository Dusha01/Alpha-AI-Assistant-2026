def found_articles_status(count: int) -> str:
    """Статус «нашёл N статей» с правильным падежом."""
    remainder = count % 100
    last = count % 10
    if last == 1 and remainder != 11:
        word = "статью"
    elif last in {2, 3, 4} and remainder not in {12, 13, 14}:
        word = "статьи"
    else:
        word = "статей"
    return f"📚 Нашёл {count} {word}, формулирую…"


