from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class QuestionCase:
    number: int
    section: str
    hero: str
    turns: tuple[str, ...]
    kind: str
    slugs: tuple[str, ...] = ()
    titles: tuple[str, ...] = ()
    facts: tuple[str, ...] = ()
    forbidden: tuple[str, ...] = ()
    copy_key: str = ""
    must: tuple[str, ...] = ()
    seed_usn: bool = False
    accept_paid: bool = False


def _case(
    number: int,
    section: str,
    hero: str,
    turns: str | tuple[str, ...],
    kind: str,
    **kwargs: object,
) -> QuestionCase:
    script = (turns,) if isinstance(turns, str) else turns
    return QuestionCase(
        number=number,
        section=section,
        hero=hero,
        turns=script,
        kind=kind,
        **kwargs,  # type: ignore[arg-type]
    )


